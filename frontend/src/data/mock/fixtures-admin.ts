const ATT_RAGAS = ["Yaman", "Bhupali", "Bhairav", "Kafi", "Des", "Malkauns", "Todi", "Bihag"];

/** Weekly attendance rows going back roughly `count` weeks (within the year). */
function makeAttendance(mksm: string, batch: string, count: number): StudentAttendanceRow[] {
  return Array.from({ length: count }, (_, i) => ({
    id: `att-${mksm}-${i}`,
    date: inDays(-(i * 7 + 3)),
    batchName: batch,
    ragaCovered: ATT_RAGAS[i % ATT_RAGAS.length],
    present: i % 6 !== 0, // an occasional absence
  }));
}

